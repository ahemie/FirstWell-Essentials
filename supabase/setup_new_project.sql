CREATE OR REPLACE FUNCTION public.inv_staff_set(p_email text, p_name text, p_role text, p_active boolean)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare me text := public.inv_require_admin(); em text := lower(trim(coalesce(p_email, '')));
begin
  if em !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Enter a valid email'; end if;
  if p_role not in ('admin', 'staff') then raise exception 'Role must be admin or staff'; end if;
  if em = me and (p_role <> 'admin' or not p_active) and
     not exists (select 1 from public.inv_staff where role = 'admin' and active and email <> me) then
    raise exception 'You are the only admin - make someone else admin first.';
  end if;
  insert into public.inv_staff (email, name, role, active)
  values (em, nullif(trim(coalesce(p_name, '')), ''), p_role, coalesce(p_active, true))
  on conflict (email) do update set name = excluded.name, role = excluded.role, active = excluded.active;
  return jsonb_build_object('ok', true);
end $function$;

CREATE OR REPLACE FUNCTION public.inv_stock_in(p_product uuid, p_qty numeric, p_expiry date, p_note text, p_client uuid)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare e text := public.inv_require_staff(); before numeric;
begin
  if p_client is null then raise exception 'Missing request id'; end if;
  if exists (select 1 from public.inv_movements where client_id = p_client) then
    return jsonb_build_object('ok', true, 'duplicate', true);
  end if;
  if p_qty is null or p_qty <= 0 or p_qty > 100000 then raise exception 'Quantity must be between 1 and 100000'; end if;
  if p_expiry is not null and (p_expiry < date '2000-01-01' or p_expiry > date '2100-01-01') then raise exception 'Expiry date looks wrong'; end if;
  if not exists (select 1 from public.products where id = p_product) then raise exception 'Unknown product'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_product::text, 0));
  before := public.inv_batch_qty(p_product, p_expiry);
  insert into public.inv_movements (client_id, product_id, expiry_date, kind, qty_change, note, qty_before, staff_email)
  values (p_client, p_product, p_expiry, 'in', p_qty, nullif(trim(coalesce(p_note, '')), ''), before, e);
  return jsonb_build_object('ok', true, 'client_id', p_client, 'new_qty', before + p_qty);
end $function$;

CREATE OR REPLACE FUNCTION public.inv_stock_out(p_product uuid, p_qty numeric, p_reason text, p_note text, p_client uuid, p_expiry date DEFAULT NULL::date, p_pick boolean DEFAULT false)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare e text := public.inv_require_staff(); remaining numeric; avail numeric; take numeric; r record; before numeric; taken jsonb := '[]'::jsonb;
begin
  if p_client is null then raise exception 'Missing request id'; end if;
  if exists (select 1 from public.inv_movements where client_id = p_client) then
    return jsonb_build_object('ok', true, 'duplicate', true);
  end if;
  if p_qty is null or p_qty <= 0 or p_qty > 100000 then raise exception 'Quantity must be between 1 and 100000'; end if;
  if nullif(trim(coalesce(p_reason, '')), '') is null then raise exception 'Please choose a reason'; end if;
  if not exists (select 1 from public.products where id = p_product) then raise exception 'Unknown product'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_product::text, 0));
  if p_pick then
    before := public.inv_batch_qty(p_product, p_expiry);
    if before < p_qty then raise exception 'Only % in that batch', before; end if;
    insert into public.inv_movements (client_id, product_id, expiry_date, kind, qty_change, reason, note, qty_before, staff_email)
    values (p_client, p_product, p_expiry, 'out', -p_qty, trim(p_reason), nullif(trim(coalesce(p_note, '')), ''), before, e);
    taken := jsonb_build_array(jsonb_build_object('expiry', p_expiry, 'qty', p_qty));
  else
    select coalesce(sum(b.qty), 0) into avail from public.inv_batches_now(p_product) b where b.qty > 0;
    if avail < p_qty then raise exception 'Not enough stock: only % available', avail; end if;
    remaining := p_qty;
    for r in select b.expiry_date, b.qty from public.inv_batches_now(p_product) b where b.qty > 0
             order by coalesce(b.expiry_date < current_date, false), b.expiry_date nulls last loop
      take := least(r.qty, remaining);
      insert into public.inv_movements (client_id, product_id, expiry_date, kind, qty_change, reason, note, qty_before, staff_email)
      values (p_client, p_product, r.expiry_date, 'out', -take, trim(p_reason), nullif(trim(coalesce(p_note, '')), ''), r.qty, e);
      taken := taken || jsonb_build_array(jsonb_build_object('expiry', r.expiry_date, 'qty', take));
      remaining := remaining - take;
      exit when remaining <= 0;
    end loop;
  end if;
  return jsonb_build_object('ok', true, 'client_id', p_client, 'taken', taken);
end $function$;

CREATE OR REPLACE FUNCTION public.inv_undo(p_client uuid)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare e text := public.inv_require_staff(); is_admin boolean; m record; n int := 0;
begin
  select (s.role = 'admin') into is_admin from public.inv_staff s where s.email = e;
  for m in select * from public.inv_movements x
           where x.client_id = p_client and x.kind <> 'undo' and x.qty_change <> 0
             and not exists (select 1 from public.inv_movements u where u.reverses_id = x.id)
           order by x.id loop
    if not is_admin and (m.staff_email <> e or m.occurred_at < now() - interval '30 minutes') then
      raise exception 'You can only undo your own actions within 30 minutes. Ask an admin.';
    end if;
    perform pg_advisory_xact_lock(hashtextextended(m.product_id::text, 0));
    if public.inv_batch_qty(m.product_id, m.expiry_date) - m.qty_change < 0 then
      raise exception 'Cannot undo: that stock has already been used since.';
    end if;
    insert into public.inv_movements (client_id, product_id, expiry_date, kind, qty_change, reason, note, qty_before, staff_email, reverses_id)
    values (gen_random_uuid(), m.product_id, m.expiry_date, 'undo', -m.qty_change, 'Undo', null,
            public.inv_batch_qty(m.product_id, m.expiry_date), e, m.id);
    n := n + 1;
  end loop;
  if n = 0 then raise exception 'Nothing to undo (already undone?)'; end if;
  return jsonb_build_object('ok', true, 'undone', n);
end $function$;

