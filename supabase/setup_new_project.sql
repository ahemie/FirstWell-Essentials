create or replace view public.v_channel_monthly_summary with (security_invoker=true) as
 SELECT s.report_month,
    CASE WHEN s.marketplace = 'MY'::text THEN 'Shopee MY'::text ELSE 'Shopee SG'::text END AS channel,
    s.currency,
    count(*) AS activity_rows,
    sum(s.units_sold) AS units_sold,
    round(sum(s.sales_amount), 2) AS revenue,
    count(*) FILTER (WHERE s.product_id IS NOT NULL) AS matched_rows,
    round(sum(CASE WHEN s.product_id IS NOT NULL THEN s.sales_amount ELSE 0::numeric END), 2) AS matched_revenue,
    count(*) FILTER (WHERE s.product_id IS NULL) AS unmatched_rows,
    'source sales'::text AS revenue_basis
   FROM public.v_shopee_sales_clean s
  GROUP BY s.report_month, s.marketplace, s.currency
UNION ALL
 SELECT c.report_month,
    'Clinic'::text AS channel,
    'MYR'::text AS currency,
    count(*) AS activity_rows,
    sum(c.units_sold) AS units_sold,
    round(sum(c.estimated_revenue_rm), 2) AS revenue,
    count(*) FILTER (WHERE c.product_id IS NOT NULL) AS matched_rows,
    round(sum(CASE WHEN c.product_id IS NOT NULL THEN c.estimated_revenue_rm ELSE 0::numeric END), 2) AS matched_revenue,
    count(*) FILTER (WHERE c.product_id IS NULL) AS unmatched_rows,
    'estimated: units × clinic price'::text AS revenue_basis
   FROM public.clinic_movement_monthly c
  WHERE c.units_sold <> 0::numeric OR c.estimated_revenue_rm <> 0::numeric
  GROUP BY c.report_month;

create or replace view public.v_inventory_latest_summary with (security_invoker=true) as
 WITH latest AS (SELECT max(inventory_snapshots.snapshot_date) AS snapshot_date FROM public.inventory_snapshots)
 SELECT l.snapshot_date,
    count(*) AS products_with_snapshot,
    sum(s.quantity) AS total_stock_units,
    round(sum(s.stock_value_rm), 2) AS total_stock_value_rm,
    (SELECT count(*) FROM public.products) AS total_products,
    (SELECT count(*) FROM public.inventory_batches b WHERE b.snapshot_date = l.snapshot_date) AS expiry_batch_rows
   FROM latest l
     LEFT JOIN public.inventory_snapshots s ON s.snapshot_date = l.snapshot_date
  GROUP BY l.snapshot_date;

