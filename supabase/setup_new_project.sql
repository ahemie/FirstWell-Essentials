CREATE OR REPLACE FUNCTION public.inv_count_many(p_items jsonb)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare e text := public.inv_require_staff(); it jsonb; cid uuid; pid uuid; ex date; cnt numeric; before numeric; delta numeric;
        rsn text; saved int := 0; changed int := 0; dup int := 0;
begin
  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Nothing to save'; end if;
  if jsonb_array_length(p_items) > 1000 then raise exception 'Too many rows in one save (max 1000)'; end if;
  for it in select * from jsonb_array_elements(p_items) loop
    cid := (it ->> 'client_id')::uuid;
    pid := (it ->> 'product_id')::uuid;
    ex  := nullif(it ->> 'expiry', '')::date;
    cnt := (it ->> 'counted')::numeric;
    rsn := nullif(trim(coalesce(it ->> 'reason', '')), '');
    if cid is null or pid is null then raise exception 'Bad row'; end if;
    if cnt is null or cnt < 0 or cnt > 1000000 then raise exception 'Invalid count'; end if;
    if ex is not null and (ex < date '2000-01-01' or ex > date '2100-01-01') then raise exception 'Expiry date looks wrong'; end if;
    if exists (select 1 from public.inv_movements m where m.client_id = cid and m.product_id = pid
               and m.expiry_date is not distinct from ex) then
      dup := dup + 1; continue;
    end if;
    perform pg_advisory_xact_lock(hashtextextended(pid::text, 0));
    before := public.inv_batch_qty(pid, ex);
    delta := cnt - before;
    if delta <> 0 and rsn is null then raise exception 'A reason is needed for rows that differ from the system count'; end if;
    insert into public.inv_movements (client_id, product_id, expiry_date, kind, qty_change, reason, note, counted_qty, qty_before, staff_email)
    values (cid, pid, ex, 'count', delta, rsn, nullif(trim(coalesce(it ->> 'note', '')), ''), cnt, before, e);
    saved := saved + 1;
    if delta <> 0 then changed := changed + 1; end if;
  end loop;
  return jsonb_build_object('ok', true, 'saved', saved, 'changed', changed, 'duplicates', dup);
end $function$;

CREATE OR REPLACE FUNCTION public.inv_history(p_product uuid DEFAULT NULL::uuid, p_mine boolean DEFAULT false, p_limit integer DEFAULT 150)
