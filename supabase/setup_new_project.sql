CREATE OR REPLACE FUNCTION public.inv_batches_now(p_product uuid DEFAULT NULL::uuid)
 RETURNS TABLE(product_id uuid, expiry_date date, qty numeric) LANGUAGE sql STABLE SET search_path TO 'public'
AS $function$
  with d as (select max(snapshot_date) as d from public.inventory_snapshots),
  base as (
    select b.product_id, b.expiry_date, sum(b.quantity) as q
    from public.inventory_batches b, d
    where b.snapshot_date = d.d and (p_product is null or b.product_id = p_product)
    group by 1, 2
  ),
  mv as (
    select m.product_id, m.expiry_date, sum(m.qty_change) as q
    from public.inv_movements m, d
    where (m.occurred_at at time zone 'Asia/Kuala_Lumpur')::date >= coalesce(d.d, date '0001-01-01')
      and (p_product is null or m.product_id = p_product)
    group by 1, 2
  )
  select coalesce(base.product_id, mv.product_id),
         coalesce(base.expiry_date, mv.expiry_date),
         coalesce(base.q, 0) + coalesce(mv.q, 0)
  from base full outer join mv
    on base.product_id = mv.product_id and base.expiry_date is not distinct from mv.expiry_date
$function$;

CREATE OR REPLACE FUNCTION public.inv_batch_qty(p_product uuid, p_expiry date)
 RETURNS numeric LANGUAGE sql STABLE SET search_path TO 'public'
AS $function$
  select coalesce((select b.qty from public.inv_batches_now(p_product) b
                   where b.expiry_date is not distinct from p_expiry), 0)
$function$;

CREATE OR REPLACE FUNCTION public.inv_adjust(p_product uuid, p_expiry date, p_change numeric, p_reason text, p_note text, p_client uuid)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare e text := public.inv_require_staff(); before numeric;
begin
  if p_client is null then raise exception 'Missing request id'; end if;
  if exists (select 1 from public.inv_movements where client_id = p_client) then
    return jsonb_build_object('ok', true, 'duplicate', true);
  end if;
  if p_change is null or p_change = 0 or abs(p_change) > 100000 then raise exception 'Enter a quantity to add or remove'; end if;
  if nullif(trim(coalesce(p_reason, '')), '') is null then raise exception 'Please choose a reason'; end if;
  if p_expiry is not null and (p_expiry < date '2000-01-01' or p_expiry > date '2100-01-01') then raise exception 'Expiry date looks wrong'; end if;
  if not exists (select 1 from public.products where id = p_product) then raise exception 'Unknown product'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_product::text, 0));
  before := public.inv_batch_qty(p_product, p_expiry);
  if before + p_change < 0 then raise exception 'That batch only has % - cannot remove % ', before, abs(p_change); end if;
  insert into public.inv_movements (client_id, product_id, expiry_date, kind, qty_change, reason, note, qty_before, staff_email)
  values (p_client, p_product, p_expiry, 'adjust', p_change, trim(p_reason), nullif(trim(coalesce(p_note, '')), ''), before, e);
  return jsonb_build_object('ok', true, 'client_id', p_client, 'new_qty', before + p_change);
end $function$;

CREATE OR REPLACE FUNCTION public.inv_barcode_link(p_barcode text, p_product uuid, p_force boolean DEFAULT false)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare e text := public.inv_require_staff(); b text := trim(coalesce(p_barcode, '')); cur uuid; cur_name text;
begin
  if length(b) < 3 or length(b) > 64 then raise exception 'Barcode looks wrong'; end if;
  if not exists (select 1 from public.products where id = p_product) then raise exception 'Unknown product'; end if;
  select product_id into cur from public.inv_barcodes where barcode = b;
  if cur is not null and cur <> p_product and not coalesce(p_force, false) then
    select name into cur_name from public.products where id = cur;
    raise exception 'ALREADY_LINKED|%', coalesce(cur_name, 'another product');
  end if;
  insert into public.inv_barcodes (barcode, product_id, created_by) values (b, p_product, e)
  on conflict (barcode) do update set product_id = excluded.product_id, created_by = excluded.created_by;
  return jsonb_build_object('ok', true);
end $function$;

